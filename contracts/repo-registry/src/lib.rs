//! GitFi Repo Registry
//!
//! One public GitHub repository can ever mint one Repo NFT. Mints and ownership
//! claims are only accepted with a valid GitFi oracle signature over a canonical
//! Borsh envelope. This contract is intentionally narrow: it owns the deed, not
//! user funds. Fee vaults and liquidity curves are separate audited modules.
//!
//! Security properties:
//! - oracle-gated mint + claim
//! - global nonce replay protection
//! - one repo -> one token -> one deed indexes
//! - admin cannot forge a deed, only pause or rotate the oracle
//! - no cross-contract calls in the trust path
//! - every state change emits a JSON event with the signature digest

use borsh::{BorshDeserialize, BorshSerialize};
use near_sdk::collections::{LookupMap, UnorderedMap, UnorderedSet};
use near_sdk::json_types::U64;
use near_sdk::{env, near, AccountId, PanicOnDefault};
use serde::{Deserialize, Serialize};

const MAX_REPO_LEN: usize = 200;
const MAX_METADATA_LEN: usize = 512;
const MAX_SIGNATURE_AGE_NS: u64 = 30 * 60 * 1_000_000_000;

#[derive(BorshSerialize, BorshDeserialize, Clone, Debug, Serialize, Deserialize)]
#[serde(crate = "near_sdk::serde")]
pub struct DeedMessage {
    /// lowercased canonical "owner/repository"
    pub repo: String,
    pub token_id: String,
    pub owner: Option<AccountId>,
    pub metadata_uri: String,
    /// 32 random bytes generated by the oracle server
    pub nonce: [u8; 32],
    /// nanoseconds, matched against the envelope block timestamp
    pub issued_at: u64,
}

/// Oracle-signed market event. Anchors trades, claims, graduations and other
/// ledger receipts on-chain without moving user funds through this contract.
#[derive(BorshSerialize, BorshDeserialize, Clone, Debug, Serialize, Deserialize)]
#[serde(crate = "near_sdk::serde")]
pub struct AnchorMessage {
    pub kind: String,
    pub aggregate: String,
    pub digest: String,
    pub nonce: [u8; 32],
    pub issued_at: u64,
}

#[derive(BorshSerialize, BorshDeserialize, Clone, Debug, Serialize, Deserialize)]
#[serde(crate = "near_sdk::serde")]
pub struct RepoDeed {
    pub token_id: String,
    pub repo: String,
    pub owner_id: Option<AccountId>,
    pub metadata_uri: String,
    pub status: String,
    pub issued_at: u64,
    pub nonce: [u8; 32],
    pub signature_digest: String,
    pub frozen: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(crate = "near_sdk::serde")]
pub struct Nft {
    pub token_id: String,
    pub owner_id: AccountId,
    pub metadata: NftMetadata,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(crate = "near_sdk::serde")]
pub struct NftMetadata {
    pub title: String,
    pub description: String,
    pub media: Option<String>,
    pub reference: Option<String>,
    pub repo: String,
    pub issued_at: U64,
    pub status: String,
}

#[near(contract_state)]
#[derive(PanicOnDefault)]
pub struct Contract {
    pub owner_id: AccountId,
    pub oracle_public_key: Vec<u8>,
    pub paused: bool,
    pub deeds: UnorderedMap<String, RepoDeed>,
    pub repo_index: LookupMap<String, String>,
    pub token_index: LookupMap<String, String>,
    pub used_nonces: UnorderedSet<Vec<u8>>,
}

#[near]
impl Contract {
    #[init]
    pub fn new(owner_id: AccountId, oracle_public_key: Vec<u8>) -> Self {
        assert_eq!(oracle_public_key.len(), 32, "oracle key must be 32 bytes");
        Self {
            owner_id,
            oracle_public_key,
            paused: false,
            deeds: UnorderedMap::new(b"g_deeds".to_vec()),
            repo_index: LookupMap::new(b"g_repos".to_vec()),
            token_index: LookupMap::new(b"g_tokens".to_vec()),
            used_nonces: UnorderedSet::new(b"g_nonces".to_vec()),
        }
    }

    /// Mint the unique Repo NFT for a verified public repository.
    /// This is permissionless to relay; the oracle signature is the authority.
    pub fn mint_repo_deed(
        &mut self,
        repo: String,
        token_id: String,
        owner: Option<AccountId>,
        metadata_uri: String,
        nonce: [u8; 32],
        issued_at: U64,
        signature: Vec<u8>,
    ) -> RepoDeed {
        self.assert_not_paused();
        let repo_lc = normalize_repo(&repo);
        assert!(metadata_uri.len() <= MAX_METADATA_LEN, "metadata URI too long");
        assert!(!token_id.trim().is_empty(), "token id required");
        assert!(
            !self.repo_index.contains_key(&repo_lc),
            "repository already has a deed"
        );
        assert!(
            !self.token_index.contains_key(&token_id),
            "token id already used"
        );
        self.verify_envelope(&DeedMessage {
            repo: repo_lc.clone(),
            token_id: token_id.clone(),
            owner: owner.clone(),
            metadata_uri: metadata_uri.clone(),
            nonce,
            issued_at: issued_at.0,
        }, &signature);

        let digest = hex_encode(&env::sha256(
            &near_sdk::borsh::to_vec(&(repo_lc.clone(), token_id.clone(), nonce)).unwrap(),
        ));
        let deed = RepoDeed {
            token_id: token_id.clone(),
            repo: repo_lc.clone(),
            owner_id: owner.clone(),
            metadata_uri,
            status: if owner.is_some() { "staked" } else { "escrowed" }.to_string(),
            issued_at: issued_at.0,
            nonce,
            signature_digest: digest.clone(),
            frozen: false,
        };

        self.deeds.insert(&token_id, &deed);
        self.repo_index.insert(&repo_lc, &token_id);
        self.token_index.insert(&token_id, &repo_lc);
        self.consume_nonce(nonce);

        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "deed_mint",
                "repo": repo_lc,
                "token_id": token_id,
                "owner": owner.map(|value| value.to_string()),
                "digest": digest,
            })
            .to_string(),
        );
        deed
    }

    /// A community-indexed repo's escrowed deed is released only with a fresh
    /// oracle signature naming the verified owner.
    pub fn claim_repo_deed(
        &mut self,
        repo: String,
        token_id: String,
        new_owner: AccountId,
        metadata_uri: String,
        nonce: [u8; 32],
        issued_at: U64,
        signature: Vec<u8>,
    ) -> RepoDeed {
        self.assert_not_paused();
        let repo_lc = normalize_repo(&repo);
        let indexed = self.repo_index.get(&repo_lc).expect("deed not found");
        assert_eq!(indexed, token_id, "token does not belong to repo");
        let mut deed = self.deeds.get(&token_id).expect("deed not found");
        assert_eq!(deed.status, "escrowed", "deed is not escrowed");
        assert!(metadata_uri.len() <= MAX_METADATA_LEN, "metadata URI too long");

        self.verify_envelope(&DeedMessage {
            repo: repo_lc.clone(),
            token_id: token_id.clone(),
            owner: Some(new_owner.clone()),
            metadata_uri: metadata_uri.clone(),
            nonce,
            issued_at: issued_at.0,
        }, &signature);

        deed.owner_id = Some(new_owner.clone());
        deed.metadata_uri = metadata_uri;
        deed.status = "staked".to_string();
        deed.signature_digest = hex_encode(&env::sha256(
            &near_sdk::borsh::to_vec(&(repo_lc, token_id.clone(), nonce)).unwrap(),
        ));
        self.deeds.insert(&token_id, &deed);
        self.consume_nonce(nonce);

        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "deed_claim",
                "repo": deed.repo,
                "token_id": deed.token_id,
                "owner": new_owner.to_string(),
            })
            .to_string(),
        );
        deed
    }

    /// Reassign a staked deed after the real repository owner proves control with
    /// a new wallet (for example, migrating a demo/sandbox identity to a real
    /// NEAR account). Requires a fresh oracle signature naming the new owner.
    pub fn reassign_deed(
        &mut self,
        repo: String,
        token_id: String,
        new_owner: AccountId,
        metadata_uri: String,
        nonce: [u8; 32],
        issued_at: U64,
        signature: Vec<u8>,
    ) -> RepoDeed {
        self.assert_not_paused();
        let repo_lc = normalize_repo(&repo);
        let indexed = self.repo_index.get(&repo_lc).expect("deed not found");
        assert_eq!(indexed, token_id, "token does not belong to repo");
        let mut deed = self.deeds.get(&token_id).expect("deed not found");
        assert!(!deed.frozen, "deed is frozen");
        assert!(metadata_uri.len() <= MAX_METADATA_LEN, "metadata URI too long");

        self.verify_envelope(&DeedMessage {
            repo: repo_lc.clone(),
            token_id: token_id.clone(),
            owner: Some(new_owner.clone()),
            metadata_uri: metadata_uri.clone(),
            nonce,
            issued_at: issued_at.0,
        }, &signature);

        deed.owner_id = Some(new_owner.clone());
        deed.metadata_uri = metadata_uri;
        deed.status = "staked".to_string();
        deed.signature_digest = hex_encode(&env::sha256(
            &near_sdk::borsh::to_vec(&(repo_lc, token_id.clone(), nonce)).unwrap(),
        ));
        self.deeds.insert(&token_id, &deed);
        self.consume_nonce(nonce);

        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "deed_reassign",
                "repo": deed.repo,
                "token_id": deed.token_id,
                "owner": new_owner.to_string(),
            })
            .to_string(),
        );
        deed
    }

    /// Owner-only metadata update. The Repo NFT stays locked in the protocol.
    pub fn update_metadata_uri(&mut self, token_id: String, metadata_uri: String) {
        assert!(metadata_uri.len() <= MAX_METADATA_LEN, "metadata URI too long");
        let mut deed = self.deeds.get(&token_id).expect("deed not found");
        assert_eq!(
            deed.owner_id,
            Some(env::predecessor_account_id()),
            "only the verified owner can update metadata"
        );
        deed.metadata_uri = metadata_uri;
        self.deeds.insert(&token_id, &deed);
        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "deed_metadata",
                "token_id": token_id,
            })
            .to_string(),
        );
    }

    /// Called by the GitFi repo oracle when GitHub stops serving a public README
    /// or the repository is deleted/private. Only the protocol owner can relay it.
    pub fn set_frozen(&mut self, token_id: String, frozen: bool) {
        self.assert_owner();
        let mut deed = self.deeds.get(&token_id).expect("deed not found");
        deed.frozen = frozen;
        deed.status = if frozen {
            "hidden".to_string()
        } else if deed.owner_id.is_some() {
            "staked".to_string()
        } else {
            "escrowed".to_string()
        };
        self.deeds.insert(&token_id, &deed);
        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "deed_frozen",
                "token_id": token_id,
                "frozen": frozen,
            })
            .to_string(),
        );
    }

    pub fn set_paused(&mut self, paused: bool) {
        self.assert_owner();
        self.paused = paused;
        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "circuit_breaker",
                "paused": paused,
            })
            .to_string(),
        );
    }

    pub fn set_oracle_public_key(&mut self, public_key: Vec<u8>) {
        self.assert_owner();
        assert_eq!(public_key.len(), 32, "oracle key must be 32 bytes");
        self.oracle_public_key = public_key;
    }

    /// Anchor a GitFi ledger receipt (trade batch, claim, graduation, star burn)
    /// on-chain. Permissionless to relay; only a fresh oracle signature is valid.
    /// No funds move here: this is a tamper-evident audit anchor.
    pub fn anchor_event(
        &mut self,
        kind: String,
        aggregate: String,
        digest: String,
        nonce: [u8; 32],
        issued_at: U64,
        signature: Vec<u8>,
    ) {
        self.assert_not_paused();
        assert!(!kind.trim().is_empty(), "kind required");
        assert!(kind.len() <= 64, "kind too long");
        assert!(!aggregate.trim().is_empty(), "aggregate required");
        assert!(aggregate.len() <= MAX_REPO_LEN, "aggregate too long");
        assert_eq!(digest.len(), 64, "digest must be 32-byte hex");
        self.verify_anchor(&AnchorMessage {
            kind: kind.clone(),
            aggregate: aggregate.clone(),
            digest: digest.clone(),
            nonce,
            issued_at: issued_at.0,
        }, &signature);
        self.consume_nonce(nonce);
        env::log_str(
            &serde_json::json!({
                "standard": "gitfi-repo-registry/1.0",
                "event": "receipt_anchor",
                "kind": kind,
                "aggregate": aggregate,
                "digest": digest,
                "issued_at": issued_at.0,
            })
            .to_string(),
        );
    }

    // ----------------------------- NEP-171-like views -----------------------------

    pub fn nft_token(&self, token_id: String) -> Option<Nft> {
        let deed = self.deeds.get(&token_id)?;
        let owner_id = deed
            .owner_id
            .clone()
            .unwrap_or_else(|| env::current_account_id());
        Some(Nft {
            token_id: deed.token_id.clone(),
            owner_id,
            metadata: NftMetadata {
                title: format!("GitFi Repo Deed · {}", deed.repo),
                description: format!(
                    "The unique protocol deed for the {} repository token.",
                    deed.repo
                ),
                media: Some(deed.metadata_uri.clone()),
                reference: Some(deed.metadata_uri),
                repo: deed.repo,
                issued_at: U64(deed.issued_at),
                status: deed.status,
            },
        })
    }

    pub fn nft_tokens_for_owner(
        &self,
        account_id: AccountId,
        from_index: Option<u64>,
        limit: Option<u64>,
    ) -> Vec<Nft> {
        let start = from_index.unwrap_or(0) as usize;
        let max = limit.unwrap_or(50).min(100) as usize;
        self.deeds
            .iter()
            .map(|(_, deed)| deed)
            .filter(|deed| deed.owner_id.as_ref() == Some(&account_id))
            .skip(start)
            .take(max)
            .map(|deed| Nft {
                token_id: deed.token_id.clone(),
                owner_id: account_id.clone(),
                metadata: NftMetadata {
                    title: format!("GitFi Repo Deed · {}", deed.repo),
                    description: format!("The unique protocol deed for {}.", deed.repo),
                    media: Some(deed.metadata_uri.clone()),
                    reference: Some(deed.metadata_uri),
                    repo: deed.repo,
                    issued_at: U64(deed.issued_at),
                    status: deed.status,
                },
            })
            .collect()
    }

    pub fn deed_for_repo(&self, repo: String) -> Option<RepoDeed> {
        let token_id = self.repo_index.get(&normalize_repo(&repo))?;
        self.deeds.get(&token_id)
    }

    pub fn deed(&self, token_id: String) -> Option<RepoDeed> {
        self.deeds.get(&token_id)
    }

    pub fn total_deeds(&self) -> u64 {
        self.deeds.len() as u64
    }

    pub fn is_paused(&self) -> bool {
        self.paused
    }

    pub fn oracle_public_key(&self) -> Vec<u8> {
        self.oracle_public_key.clone()
    }

    // ----------------------------- internals -----------------------------

    fn verify_envelope(&mut self, message: &DeedMessage, signature: &[u8]) {
        assert_eq!(signature.len(), 64, "signature must be 64 bytes");
        assert!(
            message.issued_at <= env::block_timestamp(),
            "oracle envelope is from the future"
        );
        assert!(
            env::block_timestamp().saturating_sub(message.issued_at) <= MAX_SIGNATURE_AGE_NS,
            "oracle envelope expired"
        );
        assert!(
            !self.used_nonces.contains(&message.nonce.to_vec()),
            "oracle nonce already used"
        );
        let bytes = near_sdk::borsh::to_vec(message).expect("envelope serialization");
        let signature_array: [u8; 64] = signature.try_into().expect("64-byte signature");
        let public_key_array: [u8; 32] = self
            .oracle_public_key
            .as_slice()
            .try_into()
            .expect("32-byte oracle key");
        assert!(
            env::ed25519_verify(&signature_array, &bytes, &public_key_array),
            "invalid oracle signature"
        );
    }

    fn verify_anchor(&self, message: &AnchorMessage, signature: &[u8]) {
        assert_eq!(signature.len(), 64, "signature must be 64 bytes");
        assert!(
            message.issued_at <= env::block_timestamp(),
            "oracle envelope is from the future"
        );
        assert!(
            env::block_timestamp().saturating_sub(message.issued_at) <= MAX_SIGNATURE_AGE_NS,
            "oracle envelope expired"
        );
        assert!(
            !self.used_nonces.contains(&message.nonce.to_vec()),
            "oracle nonce already used"
        );
        let bytes = near_sdk::borsh::to_vec(message).expect("envelope serialization");
        let signature_array: [u8; 64] = signature.try_into().expect("64-byte signature");
        let public_key_array: [u8; 32] = self
            .oracle_public_key
            .as_slice()
            .try_into()
            .expect("32-byte oracle key");
        assert!(
            env::ed25519_verify(&signature_array, &bytes, &public_key_array),
            "invalid oracle signature"
        );
    }

    fn consume_nonce(&mut self, nonce: [u8; 32]) {
        let key = nonce.to_vec();
        assert!(!self.used_nonces.contains(&key), "nonce replay");
        self.used_nonces.insert(&key);
    }

    fn assert_owner(&self) {
        assert_eq!(
            env::predecessor_account_id(),
            self.owner_id,
            "protocol owner only"
        );
    }

    fn assert_not_paused(&self) {
        assert!(!self.paused, "registry is paused");
    }

}

fn hex_encode(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        let value = *byte;
        out.push(HEX[(value >> 4) as usize] as char);
        out.push(HEX[(value & 0x0f) as usize] as char);
    }
    out
}

fn normalize_repo(input: &str) -> String {
    let repo = input.trim().to_lowercase();
    assert!(repo.len() <= MAX_REPO_LEN, "repository identifier too long");
    let parts: Vec<&str> = repo.split('/').collect();
    assert_eq!(parts.len(), 2, "repository must be owner/name");
    assert!(!parts[0].is_empty() && !parts[1].is_empty(), "empty repository part");
    assert!(
        parts.iter().all(|part| part
            .chars()
            .all(|c| c.is_alphanumeric() || c == '-' || c == '_' || c == '.')),
        "invalid repository characters"
    );
    repo
}

#[cfg(test)]
mod tests {
    use super::normalize_repo;
    use std::collections::HashSet;

    #[test]
    fn normalizes_repo_paths() {
        assert_eq!(normalize_repo("Oven-Sh/Bun"), "oven-sh/bun");
        assert_eq!(normalize_repo("simonw/llm "), "simonw/llm");
    }

    #[test]
    #[should_panic]
    fn rejects_nested_paths() {
        normalize_repo("owner/repo/tree/main");
    }

    #[test]
    fn no_duplicate_repo_paths_in_envelope() {
        // This is a guardrail for code refactors: repo IDs are lowercased before signature.
        let mut seen = HashSet::new();
        assert!(seen.insert(normalize_repo("GitFi/Fun")));
        assert!(!seen.insert(normalize_repo("gitfi/fun")));
    }
}
